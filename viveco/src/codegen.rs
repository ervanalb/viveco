//! Generates Rust constants for an asset's animation, shape, and bone names,
//! for use from build scripts.
//!
//! Animation indices are positions in [`Asset::animations`], so hard-coding
//! them breaks when animations are reordered. Shape and bone names are also
//! easy to misspell. This module resolves all of that once, at build time, and
//! emits three modules:
//!
//! ```no_run
//! // build.rs
//! fn main() {
//!     viveco::codegen::emit_asset_constants("assets/stick.viveco", "stick")
//!         .expect("generate asset constants");
//! }
//! ```
//!
//! ```ignore
//! // src/main.rs
//! mod stick {
//!     include!(concat!(env!("OUT_DIR"), "/stick.rs"));
//! }
//!
//! // stick::animations::WALK is the index of the "Walk" animation.
//! // stick::shapes::HEAD and stick::bones::HEAD are their names.
//! ```
//!
//! Add `viveco` to `[build-dependencies]` with `default-features = false` so the
//! build script does not compile Bevy or Vello. The generated constants are
//! only as current as the asset at build time; if the asset can change at
//! runtime (hot reload, downloadable content), resolve names at load time
//! instead.
//!
//! [`Asset::animations`]: crate::Asset::animations

// A build script's body is `fn main`, so the doctest cannot avoid it.
#![allow(clippy::needless_doctest_main)]

use std::collections::HashSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::{Asset, Bone, Shape};

/// Reads a Viveco asset, generates its constants source, and writes the source
/// to `$OUT_DIR/{module}.rs`.
///
/// This is meant to be called from a build script. It prints
/// `cargo:rerun-if-changed` for `asset_path` and returns the path it wrote.
///
/// `module` is used as the output file name; it may contain only ASCII
/// alphanumerics and underscores.
pub fn emit_asset_constants(
    asset_path: impl AsRef<Path>,
    module: &str,
) -> Result<PathBuf, CodegenError> {
    let path = asset_path.as_ref();

    if module.is_empty()
        || !module
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_')
    {
        return Err(CodegenError::InvalidModuleName(module.to_owned()));
    }
    println!("cargo:rerun-if-changed={}", path.display());

    let asset = Asset::load_from_file(path).map_err(CodegenError::Asset)?;
    let out_dir = std::env::var_os("OUT_DIR").ok_or(CodegenError::MissingOutDir)?;
    let output = PathBuf::from(out_dir).join(format!("{module}.rs"));
    let source = format!(
        "// @generated by viveco from {}.\n// Do not edit.\n\n{}",
        path.display(),
        asset_constants_source(&asset),
    );
    std::fs::write(&output, source).map_err(CodegenError::Io)?;
    Ok(output)
}

/// Returns the generated Rust source for `asset`.
///
/// The source defines `animations`, `shapes`, and `bones` modules. Animation
/// constants are indices; shape and bone constants are their names. Entries are
/// emitted in tree order, unnamed entries and repeated names are skipped, and
/// names that sanitize to the same identifier are disambiguated with `_2`,
/// `_3`, and so on.
pub fn asset_constants_source(asset: &Asset) -> String {
    let animations = named_entries(
        asset
            .animations
            .iter()
            .enumerate()
            .map(|(index, animation)| (index, animation.name.as_str())),
    );

    let mut shape_names = Vec::new();
    visit_shapes(&asset.shapes, &mut shape_names);
    let shapes = named_entries(shape_names.into_iter().enumerate());

    let mut bone_names = Vec::new();
    visit_bones(&asset.bones, &mut bone_names);
    let bones = named_entries(bone_names.into_iter().enumerate());

    let mut out = String::new();
    write_animations(&mut out, &animations);
    out.push('\n');
    write_names(&mut out, "shapes", "shape", "shape_index_by_name", &shapes);
    out.push('\n');
    write_names(&mut out, "bones", "bone", "bone_index_by_name", &bones);
    out
}

/// One named entry with its source index and generated identifier.
struct NamedEntry {
    identifier: String,
    name: String,
    index: usize,
}

/// Deduplicates names in traversal order and assigns unique identifiers.
fn named_entries<'a>(names: impl IntoIterator<Item = (usize, &'a str)>) -> Vec<NamedEntry> {
    let mut seen_names = HashSet::new();
    let mut used_identifiers = HashSet::new();
    let mut entries = Vec::new();

    for (index, name) in names {
        if name.is_empty() || !seen_names.insert(name) {
            continue;
        }
        let Some(base) = constant_name(name) else {
            continue;
        };

        let mut identifier = base.clone();
        let mut suffix = 1;
        while !used_identifiers.insert(identifier.clone()) {
            suffix += 1;
            identifier = format!("{base}_{suffix}");
        }

        entries.push(NamedEntry {
            identifier,
            name: name.to_owned(),
            index,
        });
    }

    entries
}

fn visit_shapes<'a>(shapes: &'a [Shape], out: &mut Vec<&'a str>) {
    for shape in shapes {
        out.push(shape.name.as_str());
        visit_shapes(&shape.children, out);
    }
}

fn visit_bones<'a>(bones: &'a [Bone], out: &mut Vec<&'a str>) {
    for bone in bones {
        out.push(bone.name.as_str());
        visit_bones(&bone.children, out);
    }
}

fn write_animations(out: &mut String, entries: &[NamedEntry]) {
    out.push_str("pub mod animations {\n");
    for entry in entries {
        let (name, identifier, index) = (&entry.name, &entry.identifier, entry.index);
        let _ = writeln!(out, "    /// Index of the animation named {name:?}.");
        let _ = writeln!(out, "    #[allow(dead_code)]");
        let _ = writeln!(out, "    pub const {identifier}: usize = {index};");
        out.push('\n');
    }

    let _ = writeln!(
        out,
        "    /// Named animation indices, matching `Asset::animation_index_by_name`."
    );
    let _ = writeln!(out, "    #[allow(dead_code)]");
    let _ = write!(out, "    pub const NAMES: &[(&str, usize)] = &[");
    for entry in entries {
        let _ = write!(out, "({:?}, {}), ", entry.name, entry.index);
    }
    out.push_str("];\n\n");

    out.push_str(
        "    /// Panics in debug builds if the loaded asset no longer matches these constants.\n\
         \x20   #[allow(dead_code)]\n\
         \x20   pub fn debug_assert_matches(asset: &::viveco::Asset) {\n\
         \x20       for &(name, index) in NAMES {\n\
         \x20           debug_assert_eq!(\n\
         \x20               asset.animation_index_by_name(name),\n\
         \x20               Some(index),\n\
         \x20               \"animation `{name}` is no longer at index {index}\",\n\
         \x20           );\n\
         \x20       }\n\
         \x20   }\n\
         }\n",
    );
}

/// Writes a module of string constants for shape or bone names.
fn write_names(out: &mut String, module: &str, kind: &str, lookup: &str, entries: &[NamedEntry]) {
    let _ = writeln!(out, "pub mod {module} {{");
    for entry in entries {
        let (name, identifier) = (&entry.name, &entry.identifier);
        let _ = writeln!(out, "    /// Name of the {kind} {name:?}.");
        let _ = writeln!(out, "    #[allow(dead_code)]");
        let _ = writeln!(out, "    pub const {identifier}: &str = {name:?};");
        out.push('\n');
    }

    let _ = writeln!(out, "    /// The {kind} names in the asset.");
    let _ = writeln!(out, "    #[allow(dead_code)]");
    let _ = write!(out, "    pub const NAMES: &[&str] = &[");
    for entry in entries {
        let _ = write!(out, "{:?}, ", entry.name);
    }
    out.push_str("];\n\n");

    let _ = writeln!(
        out,
        "    /// Panics in debug builds if the loaded asset no longer has these {kind}s."
    );
    let _ = writeln!(out, "    #[allow(dead_code)]");
    let _ = writeln!(
        out,
        "    pub fn debug_assert_matches(asset: &::viveco::Asset) {{"
    );
    let _ = writeln!(out, "        for &name in NAMES {{");
    let _ = writeln!(
        out,
        "            debug_assert!(asset.{lookup}(name).is_some(), \"{kind} `{{name}}` is missing\");"
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
}

/// Converts a user-facing name into an `UPPER_SNAKE_CASE` identifier.
///
/// Returns `None` when nothing identifier-like remains.
fn constant_name(name: &str) -> Option<String> {
    let mut out = String::new();
    let mut previous = None;
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            // Split camel case: "walkCycle" -> WALK_CYCLE.
            if ch.is_ascii_uppercase()
                && previous.is_some_and(|prev: char| prev.is_ascii_lowercase())
                && !out.ends_with('_')
            {
                out.push('_');
            }
            out.push(ch.to_ascii_uppercase());
            previous = Some(ch);
        } else {
            if !out.is_empty() && !out.ends_with('_') {
                out.push('_');
            }
            previous = None;
        }
    }

    let out = out.trim_matches('_');
    if out.is_empty() {
        None
    } else if out.as_bytes()[0].is_ascii_digit() {
        Some(format!("_{out}"))
    } else {
        Some(out.to_owned())
    }
}

/// Why asset constants could not be generated.
#[derive(Debug)]
pub enum CodegenError {
    /// The asset could not be read or parsed.
    Asset(crate::AssetLoadError),
    /// Writing the generated source failed.
    Io(std::io::Error),
    /// The build script is not running under Cargo (no `OUT_DIR`).
    MissingOutDir,
    /// The module name contains characters that are not allowed in a file name.
    InvalidModuleName(String),
}

impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Asset(err) => write!(f, "{err}"),
            Self::Io(err) => write!(f, "could not write asset constants: {err}"),
            Self::MissingOutDir => {
                write!(f, "OUT_DIR is not set; call this from a build script")
            }
            Self::InvalidModuleName(name) => {
                write!(f, "invalid module name {name:?}")
            }
        }
    }
}

impl std::error::Error for CodegenError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Asset(err) => Some(err),
            Self::Io(err) => Some(err),
            Self::MissingOutDir | Self::InvalidModuleName(_) => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{Animation, Asset, Bone, Shape};

    fn animations(names: &[&str]) -> Vec<Animation> {
        names
            .iter()
            .map(|name| Animation {
                name: name.to_string(),
                ..Default::default()
            })
            .collect()
    }

    #[test]
    fn emits_animation_indices() {
        let source = asset_constants_source(&Asset {
            animations: animations(&["Wave", "Walk", "Arm Swing"]),
            ..Default::default()
        });

        assert!(source.contains("pub mod animations {"));
        assert!(source.contains("pub const WAVE: usize = 0;"));
        assert!(source.contains("pub const WALK: usize = 1;"));
        assert!(source.contains("pub const ARM_SWING: usize = 2;"));
        assert!(source.contains(
            r#"pub const NAMES: &[(&str, usize)] = &[("Wave", 0), ("Walk", 1), ("Arm Swing", 2), ];"#
        ));
        assert!(source.contains("pub fn debug_assert_matches(asset: &::viveco::Asset)"));
    }

    #[test]
    fn skips_unnamed_and_repeated_animations() {
        let source = asset_constants_source(&Asset {
            animations: animations(&["Walk", "", "Walk", "Wave"]),
            ..Default::default()
        });

        assert!(source.contains("pub const WALK: usize = 0;"));
        assert!(!source.contains("pub const WALK_2"));
        assert!(source.contains("pub const WAVE: usize = 3;"));
        assert!(source.contains(r#""Walk", 0"#));
        assert!(!source.contains(r#""Walk", 2"#));
    }

    #[test]
    fn sanitizes_names_and_disambiguates_collisions() {
        let source = asset_constants_source(&Asset {
            animations: animations(&["walkCycle", "Walk Cycle", "2D Walk", "!!!"]),
            ..Default::default()
        });

        assert!(source.contains("pub const WALK_CYCLE: usize = 0;"));
        assert!(source.contains("pub const WALK_CYCLE_2: usize = 1;"));
        assert!(source.contains("pub const _2D_WALK: usize = 2;"));
        assert!(!source.contains("!!!"));
    }

    #[test]
    fn emits_shape_and_bone_name_modules() {
        let source = asset_constants_source(&Asset {
            shapes: vec![Shape {
                name: "Body".into(),
                children: vec![Shape {
                    name: "Head".into(),
                    ..Default::default()
                }],
                ..Default::default()
            }],
            bones: vec![Bone {
                name: "Root".into(),
                children: vec![Bone {
                    name: "Head".into(),
                    ..Default::default()
                }],
                ..Default::default()
            }],
            ..Default::default()
        });

        // Same name in both modules does not collide.
        assert_eq!(source.matches("pub mod shapes {").count(), 1);
        assert_eq!(source.matches("pub mod bones {").count(), 1);
        assert!(source.contains(r#"pub const BODY: &str = "Body";"#));
        assert!(source.contains(r#"pub const HEAD: &str = "Head";"#));
        assert!(source.contains(r#"pub const ROOT: &str = "Root";"#));
        assert!(source.contains("pub const NAMES: &[&str] = &[\"Body\", \"Head\", ];"));
        assert!(source.contains("pub const NAMES: &[&str] = &[\"Root\", \"Head\", ];"));
        assert!(source.contains("asset.shape_index_by_name(name).is_some()"));
        assert!(source.contains("asset.bone_index_by_name(name).is_some()"));
    }

    #[test]
    fn skips_unnamed_and_repeated_shape_and_bone_names() {
        let source = asset_constants_source(&Asset {
            shapes: vec![
                Shape {
                    name: "Head".into(),
                    ..Default::default()
                },
                Shape {
                    name: String::new(),
                    ..Default::default()
                },
                Shape {
                    name: "Head".into(),
                    ..Default::default()
                },
            ],
            ..Default::default()
        });

        assert_eq!(
            source.matches(r#"pub const HEAD: &str = "Head";"#).count(),
            1
        );
    }

    #[test]
    fn escapes_names_in_generated_literals() {
        let source = asset_constants_source(&Asset {
            animations: animations(&[r#"A "quoted" name"#]),
            ..Default::default()
        });

        assert!(source.contains(r#"("A \"quoted\" name", 0)"#));
        assert!(source.contains(r#"pub const A_QUOTED_NAME: usize = 0;"#));
    }

    #[test]
    fn rejects_invalid_module_names() {
        let err = emit_asset_constants("unused", "../escape").unwrap_err();
        assert!(matches!(err, CodegenError::InvalidModuleName(_)));
    }
}
