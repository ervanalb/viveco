//! Compile-time conversion of `.json` documents into the compact viveco
//! binary format.
//!
//! ```ignore
//! static STICK: &[u8] = viveco::viveco!("assets/stick.json");
//! ```
//!
//! The path is resolved relative to the manifest directory of the crate that
//! invokes the macro. The macro reads the JSON, validates it, and expands to a
//! `&'static [u8]` constant, so the compiled document lives in the binary with
//! no runtime file access.

mod compile;
mod json;

use proc_macro::TokenStream;
use proc_macro2::TokenStream as TokenStream2;
use quote::quote;
use syn::{LitStr, parse_macro_input};

/// Embeds a `.json` file as a compiled `&'static [u8]`.
///
/// The generated byte string contains graphics, bones, and animations. Names
/// are removed; cross-references use array indices.
#[proc_macro]
pub fn viveco(input: TokenStream) -> TokenStream {
    let path = parse_macro_input!(input as LitStr);
    match expand(&path.value()) {
        Ok(tokens) => tokens.into(),
        Err(message) => syn::Error::new(path.span(), message)
            .to_compile_error()
            .into(),
    }
}

fn expand(relative: &str) -> Result<TokenStream2, String> {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".to_owned());
    let requested = std::path::Path::new(relative);
    let path = if requested.is_absolute() {
        requested.to_path_buf()
    } else {
        std::path::Path::new(&manifest).join(requested)
    };

    let text = std::fs::read_to_string(&path)
        .map_err(|error| format!("failed to read {}: {error}", path.display()))?;
    let document: json::Document = serde_json::from_str(&text)
        .map_err(|error| format!("failed to parse {}: {error}", path.display()))?;
    let bytes = compile::compile(&document)?;
    let literal = proc_macro2::Literal::byte_string(&bytes);

    Ok(quote! {{
        const BYTES: &[u8] = #literal;
        BYTES
    }})
}
